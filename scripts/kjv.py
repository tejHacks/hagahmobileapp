"""KJV lookups from the app's own Bible database (assets/bible/bible.db).

    python3 scripts/kjv.py fix-declarations   # rewrite `scripture:` in data/declarations.ts with exact KJV text
    python3 scripts/kjv.py scripture-declarations  # regenerate data/scripture_declarations.ts
"""
import json
import os
import re
import sqlite3
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DB = sqlite3.connect(os.path.join(ROOT, "assets/bible/bible.db"))

ALIASES = {"psalm": "Psalms", "song of solomon": "Song of Songs", "canticles": "Song of Songs"}
BOOKS = {r[0].lower(): r[0] for r in DB.execute("select distinct book_name from verses")}


def book_name(name: str) -> str:
    key = name.strip().lower()
    return ALIASES.get(key) or BOOKS.get(key) or ""


REF = re.compile(r"^\s*((?:[123]\s)?[A-Za-z ]+?)\s+(\d+):([\d,\-–\s]+)\s*$")


def verses_for(ref: str):
    """'Romans 8:37-39' -> [(37, text), ...]; supports 'a-b' and 'a,b'. Returns None when not found."""
    m = REF.match(ref)
    if not m:
        return None
    book = book_name(m.group(1))
    if not book:
        return None
    chapter = int(m.group(2))
    nums = []
    for part in re.split(r"\s*,\s*", m.group(3).replace("–", "-").strip()):
        if "-" in part:
            a, b = part.split("-")
            nums += list(range(int(a), int(b) + 1))
        elif part:
            nums.append(int(part))
    out = []
    for n in nums:
        row = DB.execute("select text from verses where book_name=? and chapter=? and verse=?", (book, chapter, n)).fetchone()
        if not row or not row[0]:
            return None
        out.append((n, clean(row[0])))
    return out


def clean(t: str) -> str:
    t = re.sub(r"\[\[.*?\]\]", "", t)  # psalm headings such as [[A Psalm of David.]]
    t = re.sub(r"^[A-Z]{2,}\.\s+", "", t.strip())  # acrostic letters such as "NUN." in Psalm 119
    t = re.sub(r"\s+", " ", t).strip()
    return t.replace(" ,", ",").replace(" .", ".").replace(" ;", ";").replace(" :", ":")


def text_for(ref: str):
    vs = verses_for(ref)
    return " ".join(t for _, t in vs) if vs else None


def ts_string(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def fix_declarations():
    path = os.path.join(ROOT, "data/declarations.ts")
    src = open(path, encoding="utf-8").read()
    fixed, missing = 0, []

    def repl(m):
        nonlocal fixed
        ref = m.group(2)
        kjv = text_for(ref)
        if not kjv:
            missing.append(ref)
            return m.group(0)
        fixed += 1
        return f'{m.group(1)}{ts_string(kjv)},'

    src = re.sub(r'(ref: "([^"]+)",\s*\n\s*scripture: )(?:"(?:[^"\\]|\\.)*"|\'(?:[^\'\\]|\\.)*\'|`[^`]*`),', repl, src)
    open(path, "w", encoding="utf-8").write(src)
    print(f"fixed {fixed}; not found: {missing}")


# First-person verses from the KJV, grouped by theme. The declaration IS the verse, word for word.
SCRIPTURE_DECLARATIONS = {
    "Identity in Christ": ["Galatians 2:20", "Psalms 139:14", "Philippians 1:21", "Romans 1:16", "Galatians 6:14", "2 Timothy 1:12", "Philippians 3:13-14", "1 Corinthians 15:10"],
    "Trust and protection": ["Psalms 23:1", "Psalms 23:4", "Psalms 27:1", "Psalms 91:2", "Psalms 18:2", "Psalms 56:3", "Psalms 56:11", "Psalms 118:6", "Psalms 4:8", "Psalms 3:5", "Psalms 121:1-2", "Isaiah 12:2"],
    "Strength and victory": ["Philippians 4:13", "Isaiah 50:7", "Habakkuk 3:19", "Psalms 18:29", "Psalms 18:32", "Psalms 118:17", "Micah 7:8", "2 Corinthians 12:10", "Psalms 144:1", "Romans 8:37"],
    "Hope and waiting": ["Lamentations 3:24", "Psalms 42:11", "Micah 7:7", "Job 19:25", "Job 13:15", "Psalms 71:14", "Psalms 130:5", "Psalms 62:5-6"],
    "Healing": ["Jeremiah 17:14", "Psalms 30:2", "Psalms 103:2-3", "Isaiah 53:5", "Psalms 73:26"],
    "Praise and joy": ["Psalms 34:1", "Psalms 103:1", "Psalms 104:33", "Habakkuk 3:18", "Isaiah 61:10", "Psalms 63:3", "Psalms 28:7", "Psalms 16:8"],
    "Guidance and the Word": ["Psalms 119:105", "Psalms 119:11", "Psalms 143:8", "Psalms 73:24", "Psalms 16:7", "Psalms 40:8"],
    "Devotion": ["Joshua 24:15", "Psalms 27:4", "Psalms 63:1", "Psalms 17:15", "Romans 8:38-39", "Psalms 116:1-2"],
}


def scripture_declarations():
    items, missing = [], []
    for theme, refs in SCRIPTURE_DECLARATIONS.items():
        for ref in refs:
            t = text_for(ref)
            if not t:
                missing.append(ref)
                continue
            display = ref.replace("Psalms ", "Psalm ")
            items.append({"theme": theme, "ref": display, "text": t})
    lines = [
        "// Generated by scripts/kjv.py from assets/bible/bible.db. Do not edit by hand.",
        "// Every declaration is a King James Version verse, word for word.",
        "",
        "export type ScriptureDeclaration = { id: string; theme: string; ref: string; text: string };",
        "",
        "export const scriptureDeclarations: ScriptureDeclaration[] = [",
    ]
    for i, it in enumerate(items):
        lines.append(f"  {{ id: \"kjv-{i + 1}\", theme: {ts_string(it['theme'])}, ref: {ts_string(it['ref'])}, text: {ts_string(it['text'])} }},")
    lines += ["];", "", "export const scriptureThemes = [" + ", ".join(ts_string(t) for t in SCRIPTURE_DECLARATIONS) + "] as const;", ""]
    open(os.path.join(ROOT, "data/scripture_declarations.ts"), "w", encoding="utf-8").write("\n".join(lines))
    print(f"wrote {len(items)}; not found: {missing}")
    return items


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "fix-declarations":
        fix_declarations()
    elif cmd == "scripture-declarations":
        for it in scripture_declarations():
            print(f"[{it['theme']}] {it['ref']}: {it['text']}")
    else:
        print(__doc__)
